/**
 * ExportServer.mjs
 *
 * Read-only HTTP server that exposes the research-data export surface.
 * Designed to run alongside the Empirica callbacks process in the
 * same container (started by `infra/scripts/empirica-entrypoint.sh`).
 *
 * Routing:
 *
 *   GET <basePath>/
 *     Server-rendered HTML list page. Top-level: batches (with game
 *     and player counts). Each batch row links to a games page; each
 *     game row links to the three download endpoints. Filters apply
 *     globally to the list via the query string.
 *
 *   GET <basePath>/batches
 *     JSON list of batches (for AJAX, machine clients).
 *
 *   GET <basePath>/batches/:batchId/games
 *     JSON list of games in the batch.
 *
 *   GET <basePath>/games/:gameId
 *     JSON metadata for a single game.
 *
 *   GET <basePath>/games/:gameId/questionnaire.csv
 *     The questionnaire CSV (redacted unless raw export is explicitly enabled).
 *
 *   GET <basePath>/games/:gameId/transcript.md
 *     The chat transcript as Markdown (redacted unless raw export is explicitly enabled).
 *
 *   GET <basePath>/games/:gameId/transcript
 *     Browser-readable formal transcript preview with Facilitator provenance.
 *
 *   GET <basePath>/games/:gameId/bundle.zip
 *     Both + meta.json + llm-audit.jsonl in one ZIP.
 *
 * Auth:
 *
 *   Every request requires HTTP Basic Authentication configured with
 *   server-side credentials. Proxy identity headers are not trusted.
 *
 * Redaction:
 *
 *   Every download response is generated by `ExportService` with
 *   `redact: true` by default. Raw export is available only when the
 *   server has explicitly enabled it.
 *
 * Filter and pagination:
 *
 *   The list page supports `?from=ISO`, `?to=ISO`, `?treatment=`,
 *   `?sequence=`, `?status=`, `?limit=`, `?offset=`. Limit is clamped
 *   to [1, 200]. Offset is non-negative. Unknown query parameters
 *   are ignored (so a stale bookmark does not break the page).
 */

import { createHash, timingSafeEqual } from "node:crypto";
import http from "node:http";

import { describeFinalDecisionOutcome, ExportService, ExportNotFoundError } from "./ExportService.mjs";
import { recordExportEvent } from "./ExportAudit.mjs";

const MAX_LIMIT = 200;
const DEFAULT_LIMIT = 25;

export function createExportServer({
  service,
  auditFile,
  authUsername,
  authPassword,
  basePath = "/",
  allowRaw = false,
  now = () => new Date().toISOString(),
} = {}) {
  if (!service) throw new Error("createExportServer: service is required");
  if (!auditFile) throw new Error("createExportServer: auditFile is required");
  if (!isNonEmptyString(authUsername) || !isNonEmptyString(authPassword)) {
    throw new Error("createExportServer: Export Basic Auth credentials are required");
  }
  const normalizedBasePath = normalizeBasePath(basePath);

  return http.createServer(async (req, res) => {
    try {
      const requester = authenticateBasic(req, { authUsername, authPassword });
      if (!requester) {
        await sendUnauthorized(res);
        return;
      }
      await route(req, res, {
        service,
        auditFile,
        now,
        requester,
        basePath: normalizedBasePath,
        allowRaw: Boolean(allowRaw),
      });
    } catch (error) {
      if (error instanceof ExportNotFoundError) {
        await sendJson(res, 404, { error: error.message });
        return;
      }
      // eslint-disable-next-line no-console
      console.error("[export-server] request failed", error);
      try {
        await sendJson(res, 500, { error: "internal error" });
      } catch {
        // socket already torn down
      }
    }
  });
}

async function route(req, res, ctx) {
  const url = new URL(req.url, "http://localhost");
  const path = stripBasePath(url.pathname, ctx.basePath);
  const search = Object.fromEntries(url.searchParams);
  const sourceIp = readSourceIp(req);
  const userAgent = req.headers["user-agent"] || "unknown";
  const rawRequested = isTruthyRaw(search.raw);
  const redact = !rawRequested;
  const auditFields = { requester: ctx.requester, sourceIp, userAgent };

  if (req.method !== "GET" && req.method !== "HEAD") {
    await sendJson(res, 405, { error: "method not allowed" });
    return;
  }

  if (path === null) {
    await sendJson(res, 404, { error: "not found" });
    return;
  }

  if (rawRequested && !ctx.allowRaw) {
    await sendJson(res, 403, { error: "raw export is disabled" });
    return;
  }

  if (ctx.basePath !== "/" && url.pathname === ctx.basePath) {
    sendHeaders(res, 308, { location: `${ctx.basePath}/${url.search}` });
    res.end();
    return;
  }

  if (path === "/" || path === "/index.html") {
    await handleListPage(req, res, ctx, search, auditFields, redact);
    return;
  }
  if (path === "/batches") {
    await handleBatchesJson(req, res, ctx, search, auditFields, redact);
    return;
  }
  const batchGames = path.match(/^\/batches\/([^/]+)\/games$/);
  if (batchGames) {
    await handleBatchGamesJson(req, res, ctx, batchGames[1], search, auditFields, redact);
    return;
  }
  const transcriptView = path.match(/^\/games\/([^/]+)\/transcript$/);
  if (transcriptView) {
    await handleTranscriptView(req, res, ctx, transcriptView[1], redact, auditFields);
    return;
  }
  const gameDetail = path.match(/^\/games\/([^/]+)$/);
  if (gameDetail) {
    await handleGameJson(req, res, ctx, gameDetail[1], auditFields);
    return;
  }
  const questionnaireCsv = path.match(/^\/games\/([^/]+)\/questionnaire\.csv$/);
  if (questionnaireCsv) {
    await handleQuestionnaireCsv(req, res, ctx, questionnaireCsv[1], redact, auditFields);
    return;
  }
  const transcriptMd = path.match(/^\/games\/([^/]+)\/transcript\.md$/);
  if (transcriptMd) {
    await handleTranscriptMd(req, res, ctx, transcriptMd[1], redact, auditFields);
    return;
  }
  const bundleZip = path.match(/^\/games\/([^/]+)\/bundle\.zip$/);
  if (bundleZip) {
    await handleBundleZip(req, res, ctx, bundleZip[1], redact, auditFields);
    return;
  }
  await sendJson(res, 404, { error: "not found" });
}

async function handleListPage(req, res, ctx, search, auditFields, redact) {
  const filter = parseListFilter(search);
  const batchLimit = clampInt(search.limit, DEFAULT_LIMIT, 1, MAX_LIMIT);
  const batches = await ctx.service.listBatches(filter);
  const trimmed = batches.slice(0, batchLimit);
  const gamesByBatch = await Promise.all(
    trimmed.map(async (b) => {
      const games = await ctx.service.listGames(b.id, { limit: MAX_LIMIT, offset: 0 });
      return { batchId: b.id, games: games.items };
    }),
  );
  const html = renderListPage({
    batches: trimmed,
    gamesByBatch,
    filter,
    limit: batchLimit,
    basePath: ctx.basePath,
    allowRaw: ctx.allowRaw,
  });
  await recordExportEvent({
    auditFile: ctx.auditFile,
    record: { ...auditFields, endpoint: "list-batches", format: "html", redact, filter, sizeBytes: Buffer.byteLength(html, "utf8") },
  });
  await sendHtml(res, 200, html);
}

async function handleBatchesJson(req, res, ctx, search, auditFields, redact) {
  const filter = parseListFilter(search);
  const items = await ctx.service.listBatches(filter);
  await recordExportEvent({
    auditFile: ctx.auditFile,
    record: { ...auditFields, endpoint: "batches.json", format: "json", redact, filter },
  });
  await sendJson(res, 200, { items, filter });
}

async function handleBatchGamesJson(req, res, ctx, batchId, search, auditFields, redact) {
  const filter = parseListFilter(search);
  filter.limit = clampInt(search.limit, DEFAULT_LIMIT, 1, MAX_LIMIT);
  filter.offset = clampInt(search.offset, 0, 0, 1_000_000);
  const result = await ctx.service.listGames(batchId, filter);
  await recordExportEvent({
    auditFile: ctx.auditFile,
    record: { ...auditFields, endpoint: "batch-games.json", batchId, format: "json", redact, filter },
  });
  await sendJson(res, 200, result);
}

async function handleGameJson(req, res, ctx, gameId, auditFields) {
  const bundle = await ctx.service.getGameBundle(gameId);
  const summary = {
    id: bundle.game.id,
    treatment: bundle.game.treatment,
    sequenceId: bundle.game.sequenceId,
    startedAt: bundle.game.startedAt,
    endedAt: bundle.game.endedAt,
    status: bundle.game.status,
    playerCount: bundle.players.length,
    roundCount: bundle.rounds.length,
    llmLogEntryCount: bundle.llmLog.length,
    players: bundle.players.map((p) => ({ id: p.id, name: p.name })),
  };
  await recordExportEvent({
    auditFile: ctx.auditFile,
    record: { ...auditFields, endpoint: "game.json", gameId, format: "json", redact: true },
  });
  await sendJson(res, 200, summary);
}

async function handleQuestionnaireCsv(req, res, ctx, gameId, redact, auditFields) {
  const { csv } = await ctx.service.renderQuestionnaireCsv(gameId, { redact });
  const sha = createHash("sha256").update(csv).digest("hex");
  const size = Buffer.byteLength(csv, "utf8");
  // Write the audit record before flushing the response so the test
  // (and any downstream consumer that reads the audit immediately
  // after a 200) sees a consistent state.
  await recordExportEvent({
    auditFile: ctx.auditFile,
    record: { ...auditFields, endpoint: "questionnaire.csv", gameId, format: "csv", redact, sizeBytes: size, sha256: sha },
  });
  sendCsvHeaders(res, { filename: `${gameId}.questionnaire.csv`, sha });
  if (req.method === "HEAD") {
    res.end();
  } else {
    res.end(csv, "utf8");
  }
}

async function handleTranscriptMd(req, res, ctx, gameId, redact, auditFields) {
  const { markdown } = await ctx.service.renderTranscriptMd(gameId, { redact });
  const sha = createHash("sha256").update(markdown).digest("hex");
  const size = Buffer.byteLength(markdown, "utf8");
  await recordExportEvent({
    auditFile: ctx.auditFile,
    record: { ...auditFields, endpoint: "transcript.md", gameId, format: "markdown", redact, sizeBytes: size, sha256: sha },
  });
  sendHeaders(res, 200, {
    "content-type": "text/markdown; charset=utf-8",
    "content-disposition": `attachment; filename="${gameId}.transcript.md"`,
    "etag": `"${sha}"`,
    "x-redact-applied": redact ? "true" : "false",
  });
  if (req.method === "HEAD") {
    res.end();
  } else {
    res.end(markdown, "utf8");
  }
}

async function handleTranscriptView(req, res, ctx, gameId, redact, auditFields) {
  const transcript = await ctx.service.getTranscriptView(gameId, { redact });
  const html = renderTranscriptPage({
    transcript,
    basePath: ctx.basePath,
    redact,
  });
  const sha = createHash("sha256").update(html).digest("hex");
  const size = Buffer.byteLength(html, "utf8");
  await recordExportEvent({
    auditFile: ctx.auditFile,
    record: { ...auditFields, endpoint: "transcript.html", gameId, format: "html", redact, sizeBytes: size, sha256: sha },
  });
  if (req.method === "HEAD") {
    sendHeaders(res, 200, { "content-type": "text/html; charset=utf-8", etag: `"${sha}"` });
    res.end();
    return;
  }
  await sendHtml(res, 200, html);
}

async function handleBundleZip(req, res, ctx, gameId, redact, auditFields) {
  // We need to know size + sha256 before we can record the audit entry,
  // but the archive streams to the response as it produces bytes. Buffer
  // the entire ZIP into memory first, then atomically send the response
  // and write the audit. Real research bundles are small (<1 MB);
  // a streaming-aware audit could be added later if we need >100 MB.
  const chunks = [];
  const sink = new (await import("node:stream")).Writable({
    write(chunk, _enc, cb) {
      chunks.push(chunk);
      cb();
    },
  });
  const { bytes, sha256 } = await ctx.service.writeGameBundle(gameId, { redact, output: sink });
  await recordExportEvent({
    auditFile: ctx.auditFile,
    record: { ...auditFields, endpoint: "bundle.zip", gameId, format: "zip", redact, sizeBytes: bytes, sha256 },
  });
  res.writeHead(200, {
    "content-type": "application/zip",
    "content-disposition": `attachment; filename="${gameId}.bundle.zip"`,
    "content-length": String(bytes),
    "x-redact-applied": redact ? "true" : "false",
  });
  if (req.method === "HEAD") {
    res.end();
    return;
  }
  res.end(Buffer.concat(chunks));
}

// ── Helpers ─────────────────────────────────────────────────────────────

function parseListFilter(search) {
  const out = {};
  if (typeof search.from === "string" && search.from) out.fromISO = search.from;
  if (typeof search.to === "string" && search.to) out.toISO = search.to;
  if (typeof search.status === "string" && search.status) out.status = search.status;
  if (typeof search.treatment === "string" && search.treatment) out.treatment = search.treatment;
  if (typeof search.sequence === "string" && search.sequence) out.sequenceId = search.sequence;
  return out;
}

function clampInt(value, fallback, min, max) {
  if (value === undefined || value === null || value === "") return fallback;
  const n = Number(value);
  if (!Number.isFinite(n)) return fallback;
  return Math.max(min, Math.min(max, Math.trunc(n)));
}

function authenticateBasic(req, { authUsername, authPassword }) {
  const header = req.headers.authorization;
  if (typeof header !== "string") return null;
  const match = /^Basic\s+([^\s]+)$/i.exec(header);
  if (!match) return null;
  let decoded;
  try {
    decoded = Buffer.from(match[1], "base64").toString("utf8");
  } catch {
    return null;
  }
  const separator = decoded.indexOf(":");
  if (separator < 0) return null;
  const username = decoded.slice(0, separator);
  const password = decoded.slice(separator + 1);
  const usernameMatches = constantTimeEqual(username, authUsername);
  const passwordMatches = constantTimeEqual(password, authPassword);
  if (!usernameMatches || !passwordMatches) return null;
  return authUsername;
}

function constantTimeEqual(actual, expected) {
  const actualHash = createHash("sha256").update(String(actual), "utf8").digest();
  const expectedHash = createHash("sha256").update(String(expected), "utf8").digest();
  return timingSafeEqual(actualHash, expectedHash);
}

function isNonEmptyString(value) {
  return typeof value === "string" && value.length > 0;
}

export function normalizeBasePath(value = "/") {
  if (typeof value !== "string") throw new Error("EXPORT_BASE_PATH must be a string");
  let normalized = value.trim();
  if (!normalized || normalized === "/") return "/";
  if (!normalized.startsWith("/")) normalized = `/${normalized}`;
  normalized = normalized.replace(/\/+$/g, "");
  if (normalized.includes("?") || normalized.includes("#")) {
    throw new Error("EXPORT_BASE_PATH must be a URL path without query or fragment");
  }
  return normalized;
}

export function readExportServerConfig(env = process.env) {
  const port = Number(env.EXPORT_PORT || 3001);
  if (!Number.isInteger(port) || port < 0 || port > 65535) {
    throw new Error("EXPORT_PORT must be an integer between 0 and 65535");
  }
  const authUsername = env.EXPORT_AUTH_USERNAME;
  const authPassword = env.EXPORT_AUTH_PASSWORD;
  if (!isNonEmptyString(authUsername) || !isNonEmptyString(authPassword)) {
    throw new Error("EXPORT_AUTH_USERNAME and EXPORT_AUTH_PASSWORD are required");
  }
  return {
    port,
    host: env.EXPORT_BIND_HOST || "127.0.0.1",
    basePath: normalizeBasePath(env.EXPORT_BASE_PATH || "/exports"),
    allowRaw: env.EXPORT_ALLOW_RAW === "1" || env.EXPORT_ALLOW_RAW?.toLowerCase() === "true",
    authUsername,
    authPassword,
    auditFile: env.EXPORT_AUDIT_FILE || "/data/export-audit.jsonl",
    tajribaUrl: env.TAJRIBA_URL || "http://127.0.0.1:3000/query",
    tajribaConfig: env.TAJRIBA_CONFIG,
    tajribaSrToken: env.TAJRIBA_SRTOKEN,
  };
}

function stripBasePath(pathname, basePath) {
  if (basePath === "/") return pathname;
  if (pathname === basePath) return "/";
  if (!pathname.startsWith(`${basePath}/`)) return null;
  return pathname.slice(basePath.length);
}

function exportUrl(basePath, relativePath = "") {
  const root = basePath === "/" ? "" : basePath;
  const suffix = String(relativePath).replace(/^\/+/, "");
  return suffix ? `${root}/${suffix}` : `${root}/` || "/";
}

function isTruthyRaw(value) {
  return typeof value === "string" && ["1", "true", "yes", "on"].includes(value.toLowerCase());
}

function readSourceIp(req) {
  const cf = req.headers["cf-connecting-ip"];
  if (typeof cf === "string" && cf.length > 0) return cf;
  const xff = req.headers["x-forwarded-for"];
  if (typeof xff === "string" && xff.length > 0) return xff.split(",")[0].trim();
  return req.socket?.remoteAddress || "unknown";
}

function sendHeaders(res, status, headers) {
  res.writeHead(status, { "cache-control": "no-store", ...headers });
}

async function sendJson(res, status, payload) {
  const body = JSON.stringify(payload, null, 2);
  sendHeaders(res, status, { "content-type": "application/json; charset=utf-8" });
  if (res.req?.method === "HEAD") {
    res.end();
  } else {
    res.end(body, "utf8");
  }
}

async function sendUnauthorized(res) {
  sendHeaders(res, 401, {
    "content-type": "application/json; charset=utf-8",
    "www-authenticate": 'Basic realm="Delibra research export", charset="UTF-8"',
  });
  if (res.req?.method === "HEAD") {
    res.end();
  } else {
    res.end(JSON.stringify({ error: "authentication required" }), "utf8");
  }
}

function sendCsvHeaders(res, { filename, sha }) {
  sendHeaders(res, 200, {
    "content-type": "text/csv; charset=utf-8",
    "content-disposition": `attachment; filename="${filename}"`,
    "etag": `"${sha}"`,
  });
}

async function sendHtml(res, status, html) {
  sendHeaders(res, status, { "content-type": "text/html; charset=utf-8" });
  res.end(html, "utf8");
}

